alter table mfg_doc add column if not exists form jsonb;

/*
 * 쪽 배열이 없으면 jsonb_typeof 가 null 이고, CHECK 는 null 을 통과시킨다.
 * coalesce 로 거짓을 만든다. 정의를 고쳐도 다시 돌 때 바뀌도록 지우고 다시 건다.
 */
alter table mfg_doc drop constraint if exists mfg_doc_form_br;
alter table mfg_doc add constraint mfg_doc_form_br
  check (form is null or (kind = 'BR' and coalesce(jsonb_typeof(form -> 'pages'), '') = 'array'));

