-- ---------------------------------------------------------------------------
-- 백업 파일에 자물쇠가 걸렸는지 남긴다 (사용자 요청 2026-09-01)
--
-- 파일 자체를 암호로 잠글 수 있게 했다 (lib/backup-lock.ts). 대장에는 그
-- 사실만 적는다.
--
-- **암호는 어디에도 담지 않는다.** 담는 순간 그 자물쇠는 뜻을 잃는다 - 파일을
-- 가져간 사람이 DB 도 가져가면 열 수 있게 되고, 애초에 파일을 잠근 이유가
-- 파일이 밖으로 나가는 경우를 막자는 것이었다. 확인용 값도 두지 않는다.
-- 암호가 맞는지는 실제로 열어 보면 GCM 봉인이 답한다.
-- ---------------------------------------------------------------------------

alter table backup_log add column if not exists locked boolean not null default false;

comment on column backup_log.locked is
  '파일에 암호 자물쇠가 걸렸는가. 암호 자체는 어디에도 담지 않는다';
