--
-- 출하 승인 요청서가 로트 단위 전량 요청으로 고정되어 있었는데, 실제 업무는
-- 배치에서 생산된 규격들 중 미출고 잔여를 골라 수량을 정해 요청한다. 요청서가
-- 선택 묶음 단위가 되면서 종이마다 번호가 필요해졌고, 출고 기록이 그 번호를
-- 물고 있어야 어느 종이로 승인된 출고인지 이어진다.
--
-- ── 번호 체계 (임시 · 사용자 지시로 간이 확정) ─────────────────────────────
-- RR-{배치번호}-{발행회차 2자리}.  예 RR-B2608-0001-01
--
-- 채번 규칙(§4.10)에 대상을 추가하지 않는다. 인쇄 회차(record_print.seq)가
-- 배치·양식별로 이미 원자적으로 증가하므로 그 값을 그대로 쓴다. 번호가 종이에
-- 찍히는 순간 기록되고, 회차라서 재사용될 수 없다. 정식 체계가 필요해지면
-- numbering_target 에 추가하고 이 주석을 지운다.
--
-- ── 왜 FK 가 아닌가 ────────────────────────────────────────────────────────
-- 요청서는 종이가 정본이고 시스템에는 발행 사실(record_print)만 남는다. 출고에
-- 적는 번호는 서면 승인까지 끝난 종이의 번호를 사람이 옮겨 적는 값이다.
-- coa_no 가 서면 성적서와 시스템을 잇는 것과 같은 방식이다 (§11).
--
-- 필수로 만들지 않는다. 차단은 S01~S05 뿐이고 (§2) 이 값의 누락은 그중에 없다.
-- 비어 있으면 화면이 그대로 비워서 보여 주고, 검토는 사람이 한다.

alter table shipment add column if not exists release_request_no text;

comment on column shipment.release_request_no is
  '출하 승인 요청서 번호 (RR-배치번호-회차). 서면 승인된 종이의 번호를 옮겨 적는다';
