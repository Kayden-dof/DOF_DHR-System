--
-- ── 무엇을 세는가 ───────────────────────────────────────────────────────────
-- **계정을 들고 두드린 것만** 센다. 로그인된 기기가 지정 자리 밖에 나가 있다는
-- 뜻이고, 이 시스템에서 실제로 위험한 것은 그것 하나다.
--
-- 익명으로 두드린 것은 세지 않는다. 인터넷에 열린 주소는 훑고 다니는 기계가
-- 하루 종일 두드리므로, 그것까지 세면 표시가 늘 켜져 있다. **늘 켜져 있는
-- 표시는 알림이 아니라 가구다** - 그리고 그 속에 진짜 한 건이 묻힌다.
-- 익명 두드림은 설정 > 개요의 목록에 그대로 쌓인다.
--
-- ── 왜 14일인가 ─────────────────────────────────────────────────────────────
-- 껐다 켜는 단추를 두지 않는다. "봤다" 를 눌러 끄게 하면 그 단추가 곧 그냥
-- 누르고 지나가는 자리가 된다. 대신 스스로 식게 둔다.
--
-- 목록과 같은 14일을 본다. 창이 다르면 머리줄의 숫자와 개요의 숫자가 달라지고,
-- 같은 이름을 단 두 숫자가 다르면 읽는 사람이 둘 다 안 믿는다.
--
-- 며칠로 볼지는 부르는 쪽이 정할 수 있게 인자로 둔다 (§2.0).
-- =============================================================================

create or replace function access_block_alert(p_days int default 14)
returns int
language sql
stable
security definer
set search_path = pg_catalog, public, pg_temp as $$
  select count(*)::int
    from access_block
   where user_id is not null
     and day >= (timezone('Asia/Seoul', now()))::date - p_days
$$;

grant execute on function access_block_alert(int) to app_role;
