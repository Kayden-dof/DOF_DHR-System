-- ---------------------------------------------------------------------------
-- 제조소 소재지를 따로 받는다 (사용자 지시 2026-09-02)
--
-- 0091 이 `address` 하나만 두었다. 사업자등록증의 사업장 소재지를 거기 적었는데,
-- **GMP 제조소는 본사와 다른 자리인 것이 보통이다** (사용자 지적). 실제로 이
-- 제조소도 같은 건물의 다른 층이다.
--
-- 하나로 두면 둘 중 하나는 틀린 채로 종이에 나간다. 제조기록서에 찍히는
-- 주소는 **그 기록이 만들어진 자리**여야 한다.
--
--   address        본사 소재지. 사업자등록증의 사업장 소재지
--   plant_address  제조소 소재지. GMP 제조가 실제로 일어나는 자리
--
-- ── 무엇이 종이에 나가는가 ─────────────────────────────────────────────
-- 제조소를 먼저 적고, 본사가 그와 다를 때만 뒤에 붙인다. 같으면 두 번 적지
-- 않는다. 제조소가 비어 있으면 본사를 **이름표 없이** 적는다 - 본사 주소에
-- "제조소" 라고 이름을 달면 그것은 종이 위의 거짓말이다.
--
-- 판정하지 않는다. 어느 쪽이 옳은지 정하지 않고, 적힌 것을 적힌 이름으로
-- 옮길 뿐이다. 둘 다 비우면 아무것도 나오지 않는다.
-- ---------------------------------------------------------------------------

alter table org_brand add column if not exists plant_address text;

comment on column org_brand.address is
  '본사 소재지. 사업자등록증의 사업장 소재지';
comment on column org_brand.plant_address is
  '제조소 소재지. GMP 제조가 일어나는 자리로, 본사와 다른 것이 보통이다. '
  '인쇄물 머리에 이 주소가 먼저 나간다 (사용자 지시 2026-09-02)';
