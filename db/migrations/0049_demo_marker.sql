/* ---------------------------------------------------------------------------
   시연 자료 표시

   운영 DB 에 시연용으로 지어낸 배치 기록이 들어가 있다. 실 운영에 들어가기
   전에 반드시 비워야 하는데, 그걸 사람이 기억하는 데 맡기면 언젠가 잊는다
   (사용자 지시).

   이 시스템에는 삭제가 없다 (§1). 실 기록이 한 줄이라도 들어간 뒤에 섞이면
   지어낸 기록과 진짜 기록을 갈라낼 방법이 없다. 그때는 되돌릴 수 없다.

   그래서 시연 자료를 넣을 때 표시를 함께 남기고, 표시가 있는 동안 모든 화면
   맨 위에 띠를 띄운다. 눈에 거슬리는 것이 목적이다 - 거슬려야 지운다.

   ── 왜 표를 하나 더 두는가 ────────────────────────────────────────────────
   기록을 보고 "이건 지어낸 것 같다" 를 추측하지 않는다. 배치번호 모양이나
   날짜로 짐작하면 진짜 기록을 지어낸 것으로 볼 수 있다. 넣은 쪽이 스스로
   남긴 표시만 믿는다.

   행은 하나뿐이다. 시연 자료를 두 번 넣어도 표시는 하나다.
--------------------------------------------------------------------------- */

create table if not exists demo_marker (
  id        boolean primary key default true check (id),
  seeded_at timestamptz not null default now(),
  note      text
);

comment on table demo_marker is
  '시연 자료가 들어 있다는 표시. 실 운영 전에 비워야 한다. 행이 있으면 모든 화면에 띠가 뜬다';

/*
 * 읽기는 누구나, 지우기는 응용이 못 한다.
 *
 * 표시를 지우는 것은 시연 자료를 통째로 비우는 일과 같아야 한다. 화면에서
 * 표시만 지우면 자료는 남고 경고만 사라진다 - 가장 나쁜 상태다.
 * scripts/reset-db.mjs 가 DB 주인 권한으로 함께 비운다.
 */
grant select on demo_marker to app_role, app_readonly;
revoke insert, update, delete on demo_marker from app_role;
