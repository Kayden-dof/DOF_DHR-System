--
-- 새 생산 품목을 셋업할 때 "이 표준서로 한 배치를 돌리면 대략 몇 개가
-- 나오는가"를 함께 적어 둔다. 계획 참고값이지 실적이 아니다. 실제 수량은
-- 재단에서 정해지고 (§3), 예정 형명(work_order_plan)이 배치별 계획을 맡는다.
-- 이 값은 그 계획을 세울 때의 출발점이다.
--
-- 발행을 제약하지 않는다. 차단은 S01~S05 뿐이다 (§2).

alter table device_master add column if not exists expected_units int
  check (expected_units is null or expected_units > 0);

comment on column device_master.expected_units is
  '배치당 예상 생산수량 (계획 참고값). 실제는 재단에서 정해진다';
