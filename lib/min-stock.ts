/* ---------------------------------------------------------------------------
   최소 재고선을 누가 정하는가

   자재 구성표에 든 품목은 «최소 재고선 다시 셈» (suggest_min_stock, 0171 · 0172 · 0175) 이 한 배치
   소요 x 4 (개당 포장재는 고정 수량) 로 선을 잡는다. 그 밖의 품목은 사용량 셈을 제안값으로만 적고
   선은 사람이 정한다. 둘은 다시 셈이 적는 근거 문장으로 갈린다 - 재고 화면 · 품목 창 · 되돌리기
   동작이 같은 셈을 쓰도록 여기 한 곳에 둔다.
--------------------------------------------------------------------------- */

/** 이 근거면 다시 셈이 선을 정하는 품목이다 (구성표 4배치 · 포장재 고정 수량) */
export const BOM_BASIS_RE = /x 4 배치|포장재 최소 수량/;

/** DB 쪽 같은 조건 (정규식). 되돌리기 동작이 쓴다 */
export const BOM_BASIS_SQL = '(x 4 배치|포장재 최소 수량)';

export function bomGoverned(basis: string | null | undefined): boolean {
  return BOM_BASIS_RE.test(basis ?? '');
}
